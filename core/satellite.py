"""Read a SatelLite project (.goo.3mf) as a dragonSlide project.

A SatelLite project is a plain 3MF (meshes + one build transform per part, origin at the corner of the plate) plus
Metadata/info.json (printer, active resin script, per-part flags). Its supports and slice data are proprietary .bms blobs:
they are not read, supports are regenerated by dragonSlide. Parsed with the standard library only (trimesh's 3MF loader needs lxml).
"""
import json
import re
import zipfile
from pathlib import Path

import numpy as np
import trimesh

from .machine import PrintSettings, load_support_presets
from .project import ProjectError, machine_by_name

UNITS = {"micron": 1e-3, "millimeter": 1.0, "centimeter": 10.0, "inch": 25.4, "foot": 304.8, "meter": 1000.0}
DEFAULT_MACHINE = "ELEGOO Saturn 4 Ultra"

# ActiveScript key -> PrintSettings field. Motion values are 0 when the printer's own profile drives them: those are skipped.
SETTINGS = {
    "layerthickness": "layer_height", "tanslate_layer_count": "transition_layers", "bottomLayerCount": "bottom_layers",
    "exposureTime": "exposure", "bottomExposureTime": "bottom_exposure",
    "lightoffDelay": "light_off_delay", "bottomLightoffDelay": "bottom_light_off_delay",
    "waitaftercure": "wait_after_cure", "bottomwaittimebeforelift": "bottom_wait_after_cure",
    "bottomwaittimeafterlift": "bottom_wait_after_lift", "bottomwaittimeafterretract": "bottom_wait_before_cure",
    "light_pwm": "pwm", "bottom_light_pwm": "bottom_pwm",
    "resineDensity": "density", "resinCost": "cost",
}
MOTION = {
    "liftingDis": "lift_height", "liftingSpeed": "lift_speed", "bottomLiftDis": "bottom_lift_height",
    "bottomLiftSpeed": "bottom_lift_speed", "slowliftdis": "lift2_height", "slowliftspeed": "lift2_speed",
    "slowbottomliftdis": "bottom_lift2_height", "slowbottomliftspeed": "bottom_lift2_speed",
    "backSpeed": "retract_speed", "bottom_retract_speed": "bottom_retract_speed",
    "slowbackdis": "retract2_height", "slowbackspeed": "retract2_speed",
    "slowbottombackdis": "bottom_retract2_height", "slowbottombackspeed": "bottom_retract2_speed",
}


def _info(z: zipfile.ZipFile):
    try:
        return json.loads(z.read("Metadata/info.json"))
    except (KeyError, ValueError):
        return None


def is_satellite(path) -> bool:
    """True for a SatelLite project file (a 3MF carrying Metadata/info.json with ProjectFormat goo.3mf)."""
    p = Path(path)
    if p.suffix.lower() != ".3mf" or not p.is_file():
        return False
    try:
        with zipfile.ZipFile(p) as z:
            info = _info(z)
    except zipfile.BadZipFile:
        return False
    return isinstance(info, dict) and info.get("ProjectFormat") == "goo.3mf"


def _matrix(s: str | None) -> np.ndarray:
    """3MF transform: 12 numbers, row-vector convention (v' = v @ M + t)."""
    T = np.eye(4)
    if s:
        v = [float(x) for x in s.split()]
        if len(v) != 12:
            raise ProjectError(f"bad 3MF transform {s!r}")
        T[:3, :3] = np.array(v[:9]).reshape(3, 3).T
        T[:3, 3] = v[9:]
    return T


CHUNK = 64 << 20
STRUCT = re.compile(rb"<object\b[^>]*>|</object>|<item\b[^>]*>|<component\b[^>]*>")
VERTEX = re.compile(rb'<vertex x="([^"]*)" y="([^"]*)" z="([^"]*)"')
TRIANGLE = re.compile(rb'<triangle v1="(\d+)" v2="(\d+)" v3="(\d+)"')


def _attr(tag: bytes, name: bytes):
    m = re.search(rb'\b' + name + rb'="([^"]*)"', tag)
    return m.group(1).decode() if m else None


def _scan(z: zipfile.ZipFile):
    """Stream 3D/3dmodel.model (they reach GBs: no DOM). -> (unit factor, {id: {name, v, f, comps}}, [(objectid, transform)])."""
    objs, items, cur, unit, head = {}, [], None, 1.0, True
    rest = b""
    with z.open("3D/3dmodel.model") as fh:
        while True:
            chunk = fh.read(CHUNK)
            buf = rest + chunk
            cut = len(buf) if not chunk else buf.rfind(b">") + 1
            text, rest = buf[:cut], buf[cut:]
            if head and text:
                head = False
                u = re.search(rb'<model\b[^>]*\bunit="([^"]+)"', text)
                unit = UNITS.get(u.group(1).decode(), 1.0) if u else 1.0
            pos = 0
            for m in STRUCT.finditer(text):
                if cur is not None and m.start() > pos:
                    _feed(cur, text[pos:m.start()])
                pos = m.end()
                tag = m.group(0)
                if tag.startswith(b"</"):
                    cur = None
                elif tag.startswith(b"<object"):
                    cur = objs[_attr(tag, b"id")] = dict(name=_attr(tag, b"name"), v=[], f=[], comps=[])
                elif tag.startswith(b"<item"):
                    items.append((_attr(tag, b"objectid"), _attr(tag, b"transform")))
                elif cur is not None:
                    cur["comps"].append((_attr(tag, b"objectid"), _attr(tag, b"transform")))
            if cur is not None and pos < len(text):
                _feed(cur, text[pos:])
            if not chunk:
                return unit, objs, items


def _feed(o, data: bytes):
    v, t = VERTEX.findall(data), TRIANGLE.findall(data)
    if v:
        o["v"].append(np.array(v, dtype="S").astype(np.float64))
    if t:
        o["f"].append(np.array(t, dtype="S").astype(np.int64))


def _parts(z: zipfile.ZipFile):
    """[(name, Trimesh in plate coordinates)] for every build item of the 3MF model."""
    unit, objs, items = _scan(z)

    def geometry(oid, depth=0):
        o = objs.get(oid)
        if o is None or depth > 8:
            raise ProjectError(f"3MF object {oid!r} not found")
        if o["v"]:
            f = np.vstack(o["f"]) if o["f"] else np.empty((0, 3), np.int64)     # indices are per <mesh>: one mesh per object
            return np.vstack(o["v"]), f
        vs, fs, n = [], [], 0
        for cid, ct in o["comps"]:
            v, f = geometry(cid, depth + 1)
            T = _matrix(ct)
            vs.append(v @ T[:3, :3].T + T[:3, 3])
            fs.append(f + n)
            n += len(v)
        if not vs:
            raise ProjectError(f"3MF object {oid!r} has no geometry")
        return np.vstack(vs), np.vstack(fs)

    out = []
    for oid, tr in items:
        v, f = geometry(oid)
        T = _matrix(tr)
        v = (v @ T[:3, :3].T + T[:3, 3]) * unit
        out.append((objs[oid]["name"] or f"part{len(out) + 1}", trimesh.Trimesh(v, f, process=True)))
    if not out:
        raise ProjectError("the 3MF has no build items")
    return out


def read_satellite(src) -> tuple[dict, dict, list]:
    """Read a SatelLite .goo.3mf: (project dict, {"meshes/x.ply": ply bytes}, notes) - the same first two as read_dsl."""
    src = Path(src)
    if not is_satellite(src):
        raise ProjectError(f"{src.name} is not a SatelLite project (.goo.3mf)")
    notes = []
    with zipfile.ZipFile(src) as z:
        info = _info(z)
        parts = _parts(z)
    plat = info.get("PlatformInfo", {})
    wanted = plat.get("PlatName") or info.get("SatelLiteMachine", {}).get("PrinterType") or DEFAULT_MACHINE
    try:
        m = machine_by_name(wanted)
    except ProjectError:
        m = machine_by_name(DEFAULT_MACHINE)
        notes.append(f"printer {wanted!r} unknown, using {m.name}")

    ps = {}
    script = info.get("ActiveScript", {})
    base = PrintSettings()
    for table, skip_zero in ((SETTINGS, False), (MOTION, True)):
        for k, f in table.items():
            if k in script and not (skip_zero and not script[k]):
                v = type(getattr(base, f))(script[k])
                ps[f] = round(v, 4) if isinstance(v, float) else v
    if script.get("Scirptname"):
        ps["resin"] = str(script["Scirptname"])
    if script.get("resinType"):
        ps["resin_type"] = str(script["resinType"])

    flags = {o.get("Name"): o for o in info.get("Objects", [])}
    supported = any(o.get("HasSupport") for o in flags.values())
    sp = dict(load_support_presets()["Tree_Medium"])
    p = dict(machine=m.name, print=ps, objects=[],
             supports=dict(enabled=supported, preset="Tree_Medium", overrides={}, lift=float(sp.get("lift_height", 0.0)) if supported else 0.0))
    # SatelLite's origin is a corner of the plate, dragonSlide's the centre; Z is dropped (parts always sit on the plate)
    cx = (plat.get("Platform", {}).get("X") or m.bed_x) / 2
    cy = (plat.get("Platform", {}).get("Y") or m.bed_y) / 2
    meshes = {}
    for i, (name, mesh) in enumerate(parts):
        b = mesh.bounds
        stem = re.sub(r"[^\w.-]", "_", name)
        rel = f"meshes/{stem}_{i}.ply"
        meshes[rel] = mesh.export(file_type="ply")
        p["objects"].append(dict(name=name, mesh=rel, x=float((b[0][0] + b[1][0]) / 2 - cx), y=float((b[0][1] + b[1][1]) / 2 - cy),
                                 rx=0.0, ry=0.0, rz=0.0, sx=1.0, sy=1.0, sz=1.0))
    if supported:
        notes.append("SatelLite supports not read: dragonSlide supports (Tree_Medium) enabled and regenerated")
    notes.append(f"{len(parts)} parts, printer {m.name}, resin {ps.get('resin', '?')}")
    return p, meshes, notes
